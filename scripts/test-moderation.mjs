#!/usr/bin/env node
/**
 * 自由投稿の判定器のテスト。`npm run test:moderation` で実行する。
 *
 * **なぜ必要か**: 自由投稿は機械の判定だけで自動公開される。
 * 判定器が空振りしていても、投稿がゼロのうちは誰も気づけない。
 * 「作った検査を一度も実行しない」を何度も繰り返しているので、
 * ここは `npm run qa` から呼んで飛ばせない場所に置く。
 *
 * 見るのは2方向:
 *   1. **通すべきものを止めていないか**(これを落とすと投稿が集まらない)
 *   2. **止めるべきものを通していないか**(これを落とすと法的リスクになる)
 */
import { classifyPost } from '../src/lib/moderation.ts';

/** [本文, 期待する severity, 何を確かめているか] */
const CASES = [
  // --- 通すべきもの(勉強中の人が実際に書く内容) ---
  ['危険物の法令が覚えられません。指定数量の計算でいつも間違えます', 'ok', '典型的なつまずき'],
  ['あと2週間で試験なのに物化がまったく手につかない。みんなどう進めてますか', 'ok', '進捗と質問'],
  ['テキスト3周したけど模試が6割止まりです。過去問に切り替えるべきでしょうか', 'ok', '勉強法の相談'],
  ['受けてきました。法令は素直だったけど物化が思ったより重かったです', 'ok', '試験の感想(問題の再現は無い)'],
  ['簿記2級の工業簿記、標準原価計算の差異分析でいつも符号を逆にします', 'ok', '専門用語を含む相談'],
  ['独学で3ヶ月やって受かりました。1日1時間くらいです', 'ok', '合格報告に近い自由文'],
  ['FPの実技、資産設計提案業務を選びました。過去問は何年分やりましたか', 'ok', '業務名を含む質問'],

  // --- 止めるべきもの ---
  ['詳しくはこちら https://example.com/kouza から登録してください', 'reject', 'URL(外部誘導)'],
  ['質問あれば連絡ください。LINE ID: study2026 まで', 'reject', '連絡先'],
  ['この教材で誰でも稼げます。月収50万も可能です', 'reject', '情報商材の勧誘'],
  ['こんな問題も解けないやつは死ねよ', 'reject', '誹謗中傷'],
  ['あああああああああああああああああああ', 'reject', '荒らし'],
  ['短い', 'reject', '10文字未満'],

  // --- 保留すべきもの(灰色。公開しないが保存はする) ---
  [
    '問3の答えは②でした。①静電気 ②摩擦熱 ③直射日光 ④酸化熱 で迷った人多いはず',
    'hold',
    '試験問題の再現(著作権)',
  ],
  [
    '出た問題を書いておきます 1.指定数量の倍数 2.保安距離 3.予防規程 4.定期点検 5.移送の基準',
    'hold',
    '選択肢の羅列',
  ],
];

let ng = 0;
console.log('\n  自由投稿の判定器');
console.log('  ' + '-'.repeat(66));

for (const [text, want, why] of CASES) {
  const got = classifyPost(text).severity;
  const ok = got === want;
  if (!ok) ng += 1;
  const badge = ok ? '\x1b[32mPASS\x1b[0m' : '\x1b[31mFAIL\x1b[0m';
  const detail = ok ? '' : ` \x1b[31m(期待 ${want} / 実際 ${got})\x1b[0m`;
  console.log(`  ${badge}  ${why}${detail}`);
  if (!ok) console.log(`        本文: ${text.slice(0, 50)}`);
}

console.log('  ' + '-'.repeat(66));
if (ng > 0) {
  console.log(`  \x1b[31m${ng} / ${CASES.length} 件が期待と違う\x1b[0m\n`);
  process.exit(1);
}
console.log(`  \x1b[32m全 ${CASES.length} 件が期待どおり\x1b[0m\n`);
